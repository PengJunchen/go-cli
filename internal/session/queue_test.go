func TestSubmissionQueue_Concurrent(t *testing.T) {
	defer verify.AssertNoGoroutineLeak(t)()

	q := NewDefaultSubmissionQueue()
	const n = 50

	var wg sync.WaitGroup
	wg.Add(n)
	for i := 0; i < n; i++ {
		go func(i int) {
			defer wg.Done()
			require.NoError(t, q.Enqueue(QueueSteering, QueuedSubmission{
				ID:      "s" + itoa(i),
				Content: "content",
			}))
		}(i)
	}
	wg.Wait()

	assert.Equal(t, n, q.Len(QueueSteering))

	wg.Add(n)
	for i := 0; i < n; i++ {
		go func() {
			defer wg.Done()
			_, ok := q.Dequeue(QueueSteering)
			require.True(t, ok)
		}()
	}
	wg.Wait()

	assert.Equal(t, 0, q.Len(QueueSteering))
}

// itoa is a minimal int-to-string helper to avoid importing strconv.
func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	var buf [20]byte
	pos := len(buf)
	neg := i < 0
	if neg {
		i = -i
	}
	for i > 0 {
		pos--
		buf[pos] = byte('0' + i%10)
		i /= 10
	}
	if neg {
		pos--
		buf[pos] = '-'
	}
	return string(buf[pos:])
}

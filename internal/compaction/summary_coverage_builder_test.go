func TestCoverageLatestUserUsesProviderVisibleTextBlocks(t *testing.T) {
	items := coverageHistory()
	items[9].Content = "shadowed-content-must-not-win"
	items[9].ContentBlocks = []llm.ContentBlock{{Type: "text", Text: "first provider-visible requirement"}, {Type: "text", Text: "second provider-visible requirement"}}
	capture := &coverageCapture{summary: "accepted"}
	result, err := NewSummaryCompactor(capture).Compact(context.Background(), items, 2500, NewCompositeTokenEstimator(0))
	if err != nil || result.NewProjection == nil || len(capture.prompts) != 1 {
		t.Fatalf("expected accepted summary: result=%+v calls=%d err=%v", result, len(capture.prompts), err)
	}
	prompt := capture.prompts[0]
	if !strings.Contains(prompt, "first provider-visible requirement") || !strings.Contains(prompt, "second provider-visible requirement") || strings.Contains(prompt, "shadowed-content-must-not-win") {
		t.Error("summary did not include the latest user's provider-visible text blocks in order")
	}
	if strings.Index(prompt, "first provider-visible requirement") >= strings.Index(prompt, "second provider-visible requirement") {
		t.Error("summary changed the order of provider-visible text blocks")
	}
}

func TestCoverageUserBlockRenderingMatchesVisibleTextAndImageOmission(t *testing.T) {
	for _, test := range []struct {
		name   string
		blocks []llm.ContentBlock
		want   []string
		image  bool
	}{
		{name: "empty blocks shadow content", blocks: []llm.ContentBlock{}},
		{name: "image remains explicitly omitted", blocks: []llm.ContentBlock{{Type: "text", Text: "visible-text"}, {Type: "image_url", ImageURL: &llm.ImageURL{URL: "https://example.invalid/private-image"}}}, want: []string{"visible-text", "[image content omitted]"}, image: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			items := coverageHistory()
			items[9].Content = "shadowed-content-must-not-win"
			items[9].ContentBlocks = test.blocks
			rendered, included := renderSummaryItem(items[9])
			if !included {
				t.Fatal("user evidence was not rendered")
			}
			if strings.Contains(rendered, "shadowed-content-must-not-win") || strings.Contains(rendered, "private-image") {
				t.Fatal("renderer exposed shadow content or omitted image URL")
			}
			for _, want := range test.want {
				if !strings.Contains(rendered, want) {
					t.Errorf("rendered item missing %q", want)
				}
			}
			original, err := imageGroupPayload(items)
			if err != nil {
				t.Fatal(err)
			}
			capture := &coverageCapture{summary: "accepted"}
			result, err := NewSummaryCompactor(capture).Compact(context.Background(), items, 2500, NewCompositeTokenEstimator(0))
			if test.image {
				if !errors.Is(err, ErrImageCompactionBlocked) || result.NewProjection != nil || len(capture.prompts) != 0 {
					t.Fatalf("image-bearing user evidence must block before summarizer: calls=%d projection=%v err=%v", len(capture.prompts), result.NewProjection, err)
				}
				after, encodeErr := imageGroupPayload(items)
				if encodeErr != nil {
					t.Fatal(encodeErr)
				}
				if !reflect.DeepEqual(original, after) {
					t.Fatal("blocked compaction mutated its original input or source")
				}
				retained, encodeErr := imageGroupPayload(result.Items)
				if encodeErr != nil {
					t.Fatal(encodeErr)
				}
				if !reflect.DeepEqual(original, retained) {
					t.Fatal("blocked compaction did not retain original user image evidence")
				}
				return
			}
			if err != nil || result.NewProjection == nil || len(capture.prompts) != 1 {
				t.Fatalf("expected accepted text-only summary: calls=%d err=%v", len(capture.prompts), err)
			}
			prompt := capture.prompts[0]
			if strings.Contains(prompt, "shadowed-content-must-not-win") || strings.Contains(prompt, "private-image") {
				t.Fatal("summary exposed shadow content or omitted image URL")
			}
			for _, want := range test.want {
				if !strings.Contains(prompt, want) {
					t.Errorf("summary missing %q", want)
				}
			}
		})
	}
}

func TestCoverageLongOrdinaryReceiptKeepsUTF8AndOutcomeHeader(t *testing.T) {
	items := []TurnItem{
		{Role: RoleUser, Content: "old question"},
		{Role: RoleAssistant, ToolCalls: []llm.ToolCall{{ID: "read", Name: "read"}}},
		{Role: RoleTool, ToolCallID: "read", ToolName: "read", ReceiptOutcome: "success", ToolResult: "BEGIN-" + strings.Repeat("汉", 500) + "-END"},
		{Role: RoleUser, Content: "current"},
	}
	capture := &coverageCapture{summary: "accepted"}
	result, err := NewSummaryCompactor(capture, WithMaxSummaryItemTokens(100)).Compact(context.Background(), items, 200, runeCountEstimator{})
	if err != nil || result.Strategy != StrategySummary || len(capture.prompts) != 1 {
		t.Fatalf("expected accepted summary: result=%+v calls=%d err=%v", result, len(capture.prompts), err)
	}
	prompt := capture.prompts[0]
	header := `[tool result name="read" outcome="success"]` + "\n"
	index := strings.Index(prompt, header)
	if index < 0 {
		t.Fatal("ordinary receipt lost its full structured header")
	}
	block := prompt[index:]
	if !utf8.ValidString(block) || utf8.RuneCountInString(block) > 100 || !strings.Contains(block, "BEGIN-") || !strings.Contains(block, "-END") || !strings.Contains(block, "[truncated]") {
		t.Errorf("ordinary receipt was not bounded at UTF-8 rune boundaries with head, tail and marker: %q", block)
	}
}

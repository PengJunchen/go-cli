func TestSubmissionQueue_EnqueueDequeueFIFO(t *testing.T) {
	defer verify.AssertNoGoroutineLeak(t)()

	q := NewDefaultSubmissionQueue()

	require.NoError(t, q.Enqueue(QueueSteering, QueuedSubmission{ID: "s1", Content: "first"}))
	require.NoError(t, q.Enqueue(QueueSteering, QueuedSubmission{ID: "s2", Content: "second"}))
	require.NoError(t, q.Enqueue(QueueSteering, QueuedSubmission{ID: "s3", Content: "third"}))

	assert.Equal(t, 3, q.Len(QueueSteering))

	item, ok := q.Dequeue(QueueSteering)
	require.True(t, ok)
	assert.Equal(t, "s1", item.ID)

	item, ok = q.Dequeue(QueueSteering)
	require.True(t, ok)
	assert.Equal(t, "s2", item.ID)

	item, ok = q.Dequeue(QueueSteering)
	require.True(t, ok)
	assert.Equal(t, "s3", item.ID)

	_, ok = q.Dequeue(QueueSteering)
	require.False(t, ok, "queue should be empty")
}

func TestSubmissionQueue_PeekDoesNotRemove(t *testing.T) {
	defer verify.AssertNoGoroutineLeak(t)()

	q := NewDefaultSubmissionQueue()
	require.NoError(t, q.Enqueue(QueueFollowUp, QueuedSubmission{ID: "f1", Content: "peek-me"}))

	item, ok := q.Peek(QueueFollowUp)
	require.True(t, ok)
	assert.Equal(t, "f1", item.ID)
	assert.Equal(t, 1, q.Len(QueueFollowUp), "Peek must not remove the item")

	// Dequeue should return the same item.
	item, ok = q.Dequeue(QueueFollowUp)
	require.True(t, ok)
	assert.Equal(t, "f1", item.ID)
	assert.Equal(t, 0, q.Len(QueueFollowUp))
}


const coverageRequirement = "NEW_REQUIREMENT: negative quantities must return ErrNegative and never be silently clamped."
const coverageFailure = "FAIL TestNegativeQuantity: negative quantity was silently accepted; expected ErrNegative."

type coverageCapture struct {
	prompts []string
	summary string
	err     error
}

func (c *coverageCapture) Summarize(_ context.Context, prompt string) (string, error) {
	c.prompts = append(c.prompts, prompt)
	return c.summary, c.err
}

func coverageHistory() []TurnItem {
	var items []TurnItem
	add := func(item TurnItem) {
		index := uint64(len(items))
		item.Runtime.Source = llm.SourceRef{Kind: llm.SourcePriorPublished, HistoryRevision: "rev", BranchID: "main", SourceEntryID: fmt.Sprint(index), PriorOrdinal: index}
		item.Runtime.ReceiptOutcome = item.ReceiptOutcome
		items = append(items, item)
	}
	group := func(index int, body, outcome string) {
		id := fmt.Sprintf("call-%d", index)
		add(TurnItem{Role: RoleAssistant, ToolCalls: []llm.ToolCall{{ID: id, Name: "bash"}}})
		add(TurnItem{Role: RoleTool, ToolCallID: id, ToolName: "bash", ReceiptOutcome: outcome, ToolResult: body})
	}
	add(TurnItem{Role: RoleUser, Content: "Inspect the package before changing it."})
	for i := 0; i < 4; i++ {
		group(i, strings.Repeat("package dependency import path\n", 500), "success")
	}
	add(TurnItem{Role: RoleUser, Content: coverageRequirement})
	group(4, coverageFailure, "error")
	for i := 5; i < 9; i++ {
		group(i, strings.Repeat("package dependency import path\n", 500), "success")
	}
	count := len(items)
	items = append(items, TurnItem{Role: RoleUser, Content: "Continue the implementation.", Runtime: llm.RuntimeMetadata{Source: llm.SourceRef{Kind: llm.SourceRunTranscript, RunID: "run", PriorSourceCount: uint64(count)}}})
	return items
}

func TestCoverageSummaryIncludesMiddleEssentialSources(t *testing.T) {
	items := coverageHistory()
	capture := &coverageCapture{summary: "summary generated by provider"}
	estimator := NewCompositeTokenEstimator(0)
	result, err := NewSummaryCompactor(capture).Compact(context.Background(), items, 2500, estimator)
	if err != nil {
		t.Fatal(err)
	}
	if len(capture.prompts) != 1 {
		t.Fatalf("summary calls = %d, want 1", len(capture.prompts))
	}
	prompt := capture.prompts[0]
	if !strings.Contains(prompt, coverageRequirement) {
		t.Error("actual summary request omitted the complete latest prior user requirement")
	}
	if !strings.Contains(prompt, coverageFailure) {
		t.Error("actual summary request omitted the complete latest error receipt")
	}
	if !utf8.ValidString(prompt) || estimateLength(prompt, estimator) > 6000 {
		t.Errorf("prompt invalid or over budget: valid=%v tokens=%d", utf8.ValidString(prompt), estimateLength(prompt, estimator))
	}
	if !strings.Contains(prompt, "[truncated]") {
		t.Error("omitted source material requires an explicit marker")
	}
	if result.NewProjection == nil || result.Strategy != StrategySummary {
		t.Fatalf("summary projection missing: %+v", result)
	}
	if got, want := result.NewProjection.Through.PriorHistoryCount, uint64(len(items)-1); got != want {
		t.Errorf("through = %d, want %d", got, want)
	}
	if result.NewProjection.Summary != capture.summary || result.Items[len(result.Items)-1].Content != "Continue the implementation." {
		t.Errorf("summary or retained current input changed: %+v", result)
	}
}

func TestCoverageEssentialOverflowStopsWithoutProjectionOrFallback(t *testing.T) {
	for _, durable := range []bool{false, true} {
		for _, over := range []string{"user", "error"} {
			for _, unified := range []bool{false, true} {
				t.Run(fmt.Sprintf("durable=%v/%s/unified=%v", durable, over, unified), func(t *testing.T) {
					items := coverageHistory()
					if over == "user" {
						items[9].Content = strings.Repeat("重要约束界", 1600)
					} else {
						items[11].ToolResult = strings.Repeat("实际失败界", 1600)
					}
					if !durable {
						for i := range items {
							items[i].Runtime = llm.RuntimeMetadata{}
						}
					}
					original := append([]TurnItem(nil), items...)
					capture := &coverageCapture{summary: "must not be generated"}
					summary := NewSummaryCompactor(capture)
					fallback := NewRecordingCompactor("fallback")
					var c Compactor = summary
					if unified {
						micro := NewRecordingCompactor("micro").WithError(ErrRequiresTruncating)
						c = NewUnifiedCompactor(WithMicro(micro), WithSummary(summary), WithTruncating(fallback))
					}
					result, err := c.Compact(context.Background(), items, 2500, runeCountEstimator{})
					if err == nil || !strings.Contains(err.Error(), "essential summary input") {
						t.Fatalf("error = %v, want essential summary input error", err)
					}
					if result.NewProjection != nil || len(capture.prompts) != 0 || len(fallback.Called()) != 0 {
						t.Fatalf("failure consumed history: result=%+v calls=%d fallback=%v", result, len(capture.prompts), fallback.Called())
					}
					if !reflect.DeepEqual(items, original) || !reflect.DeepEqual(result.Items, original) {
						t.Error("failure must return and leave the original source history unchanged")
					}
				})
			}
		}
	}
}

func TestCoverageOmissionPreservesPrioritiesOrderAndUTF8(t *testing.T) {
	items := []TurnItem{
		{Role: RoleSystem, Content: "SYSTEM-NEVER-IN-PROMPT"},
		{Role: RoleUser, Content: "old-user-" + strings.Repeat("旧", 25)},
		{Role: RoleAssistant, Content: strings.Repeat("普通", 500)},
		{Role: RoleUser, Content: "latest-user-" + strings.Repeat("新", 25)},
		{Role: RoleAssistant, ToolCalls: []llm.ToolCall{{ID: "failure", Name: "bash", Args: map[string]any{"secret": "ARGS-NEVER-IN-PROMPT"}}}},
		{Role: RoleTool, ToolCallID: "failure", ToolName: "bash", ReceiptOutcome: "error", ToolResult: "failed-失败"},
		{Role: RoleAssistant, Content: strings.Repeat("ordinary-output", 500)},
		{Role: RoleUser, Content: "prior-summary-not-latest-user", IsCompaction: true},
	}
	capture := &coverageCapture{summary: "summary"}
	c := NewSummaryCompactor(capture, WithMaxSummaryPromptTokens(500), WithMaxSummaryItemTokens(150))
	result, err := c.Compact(context.Background(), items, 150, runeCountEstimator{})
	if err != nil {
		t.Fatal(err)
	}
	if result.Strategy != StrategySummary || len(capture.prompts) != 1 {
		t.Fatalf("expected a summary call and result: %+v", result)
	}
	prompt := capture.prompts[0]
	for _, term := range []string{"old-user-", "latest-user-", "failed-失败", "[truncated]", "name=\"bash\" outcome=\"error\""} {
		if !strings.Contains(prompt, term) {
			t.Errorf("prompt missing %q: %s", term, prompt)
		}
	}
	for _, secret := range []string{"SYSTEM-NEVER-IN-PROMPT", "ARGS-NEVER-IN-PROMPT"} {
		if strings.Contains(prompt, secret) {
			t.Errorf("prompt exposed %q", secret)
		}
	}
	if !(strings.Index(prompt, "old-user-") < strings.Index(prompt, "latest-user-") && strings.Index(prompt, "latest-user-") < strings.Index(prompt, "failed-失败")) {
		t.Error("selected source material must remain in original order")
	}
	if !utf8.ValidString(prompt) || estimateLength(prompt, runeCountEstimator{}) > 500 {
		t.Errorf("prompt invalid or over budget: valid=%v tokens=%d", utf8.ValidString(prompt), estimateLength(prompt, runeCountEstimator{}))
	}
}


func TestSubmissionQueue_Drain(t *testing.T) {
	defer verify.AssertNoGoroutineLeak(t)()

	q := NewDefaultSubmissionQueue()
	require.NoError(t, q.Enqueue(QueueNextRun, QueuedSubmission{ID: "n1", Content: "a"}))
	require.NoError(t, q.Enqueue(QueueNextRun, QueuedSubmission{ID: "n2", Content: "b"}))
	require.NoError(t, q.Enqueue(QueueNextRun, QueuedSubmission{ID: "n3", Content: "c"}))

	items := q.Drain(QueueNextRun)
	require.Len(t, items, 3)
	assert.Equal(t, "n1", items[0].ID)
	assert.Equal(t, "n2", items[1].ID)
	assert.Equal(t, "n3", items[2].ID)
	assert.Equal(t, 0, q.Len(QueueNextRun), "queue must be empty after drain")
}

